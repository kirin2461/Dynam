  // ── Модалка ───────────────────────────────────────────────────────────
  function esc(s) {
    return String(s).replace(/[&<>"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
  }

  function showHelp(key) {
    const t = HELP_TOPICS[key];
    if (!t) return;
    closeHelp();
    const ov = document.createElement('div');
    ov.className = 'help-overlay';
    ov.id = 'help-overlay';
    ov.innerHTML =
      '<div class="help-modal">' +
        '<button class="help-close" onclick="document.getElementById(\'help-overlay\').remove()">×</button>' +
        '<h3>' + esc(t.title) + '</h3>' +
        '<h4>Что это</h4><p>' + esc(t.what) + '</p>' +
        '<h4>Как пользоваться</h4>' + t.how +
        '<h4>Когда это нужно</h4><p>' + esc(t.when) + '</p>' +
        (t.warn ? '<h4>Осторожно</h4><div class="help-warn"><p>' + esc(t.warn) + '</p></div>' : '') +
      '</div>';
    ov.addEventListener('click', (e) => { if (e.target === ov) ov.remove(); });
    document.body.appendChild(ov);
  }
  window.showHelp = showHelp;

  function closeHelp() {
    const el = document.getElementById('help-overlay');
    if (el) el.remove();
  }

  // ── Раздел «Справка»: карточки всех тем ───────────────────────────────
  function renderHelpGrid() {
    const grid = document.getElementById('help-grid');
    if (!grid) return;
    grid.innerHTML = Object.keys(HELP_TOPICS).map(k => {
      const t = HELP_TOPICS[k];
      return '<div class="help-card" onclick="showHelp(\'' + k + '\')">' +
               '<div class="help-card__title">' + esc(t.title) + '</div>' +
               '<div class="help-card__hint">' + esc(t.hint) + '</div>' +
             '</div>';
    }).join('');
  }

  // ── Кнопки «?» в заголовках разделов ──────────────────────────────────
  function injectHelpButtons() {
    Object.keys(SECTION_HELP).forEach(sec => {
      const h = document.querySelector('#sec-' + sec + ' .section-title');
      if (!h || h.querySelector('.help-btn')) return;
      const b = document.createElement('button');
      b.className = 'help-btn';
      b.type = 'button';
      b.title = 'Справка: что это и как пользоваться';
      b.textContent = '?';
      b.addEventListener('click', (e) => {
        e.stopPropagation();
        showHelp(SECTION_HELP[sec]);
      });
      h.appendChild(b);
    });
  }

  // ── Инициализация ─────────────────────────────────────────────────────
  function init() {
    const style = document.createElement('style');
    style.textContent = css;
    document.head.appendChild(style);
    injectHelpButtons();
    renderHelpGrid();
    document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeHelp(); });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
